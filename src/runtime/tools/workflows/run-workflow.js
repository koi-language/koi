/**
 * Run Workflow Action — Instantiate a workflow's steps as concrete tasks.
 *
 * Workflows surface to the agent as BARE NAMES in the system prompt
 * (no description). Before invoking, the agent should call
 * `describe_workflow(name)` to read the description and confirm intent.
 * This tool then translates the workflow's prose script into concrete
 * tasks via a cheap LLM and fires `planner.result` so the System
 * coordinator transitions into running_plan.
 */

import fs from 'fs';
import path from 'path';
import { channel } from '../../io/channel.js';
import { fireReaction } from '../../agent/reactions.js';
import {
  listWorkflowsCatalog,
  readWorkflowBody,
} from '../../state/workflows-catalog.js';

/** Enumerate the workflow's sibling files. The agent that runs each task
 *  receives this list (via the WORKFLOW WORKSPACE block prepended to the
 *  task description) so it can `read_file(<absolute path>)` on a sibling
 *  the workflow body mentions by name (e.g. `STORYBOARD_ANATOMY.md`,
 *  `STYLE_PRESETS.md`) instead of grep-failing in the project's cwd. */
function listWorkflowFiles(directory) {
  if (!directory) return [];
  const out = [];
  try {
    const entries = fs.readdirSync(directory, { withFileTypes: true });
    for (const ent of entries) {
      // Skip the WORKFLOW.md itself (already inlined as the body) and
      // hidden / nested directories — workflow assets live as top-level
      // siblings of WORKFLOW.md. Subdirectories are reported as bare
      // names so the agent knows they exist without us walking them.
      if (ent.name === 'WORKFLOW.md') continue;
      if (ent.name.startsWith('.')) continue;
      const abs = path.join(directory, ent.name);
      if (ent.isDirectory()) {
        out.push({ path: abs, kind: 'dir' });
      } else {
        out.push({ path: abs, kind: 'file' });
      }
    }
  } catch { /* unreadable workflow dir — non-fatal, return what we have */ }
  return out;
}

/** Render the WORKFLOW WORKSPACE block prepended to every task. Mirrors
 *  what the skill activation returns (`directory` + `resources`) so an
 *  agent that opens a workflow task can resolve relative file mentions
 *  in the workflow body to absolute paths. */
function workspaceBlock(workflow, files) {
  if (!workflow?.directory) return '';
  const lines = [
    '## WORKFLOW WORKSPACE',
    `This task was generated by the **${workflow.name}** workflow.`,
    `Workflow directory: \`${workflow.directory}\``,
  ];
  if (files.length > 0) {
    lines.push('Files in the workflow directory (any reference in the workflow body to a sibling file resolves to one of these absolute paths — read_file with the FULL path, do NOT search the project root for it):');
    for (const f of files) {
      lines.push(`- \`${f.path}\`${f.kind === 'dir' ? '/' : ''}`);
    }
  } else {
    lines.push('(No sibling files in the workflow directory beyond WORKFLOW.md.)');
  }
  return lines.join('\n');
}

async function runTranslator(agent, workflow, body, userMessage, files) {
  const { resolve: resolveModel } = await import('../../llm/providers/factory.js');

  // Delegate model selection to the factory — same pattern as call-llm.js
  // and the rest of the runtime. The factory handles:
  //   • picking the best non-thinking candidate for taskType=reasoning at
  //     this difficulty (preserves the old getAllCandidates intent),
  //   • the gateway-mode `effectiveProvider='openai'` wrapping when
  //     KOI_AUTH_TOKEN is set (so the original model name still routes
  //     correctly through the gateway to its real backend),
  //   • boost / cooldown / forced-model overrides automatically.
  //
  // Previously this site hand-rolled getAllCandidates + a manual
  // `effectiveProvider = KOI_AUTH_TOKEN ? 'openai' : ...` shim that
  // duplicated the factory's logic and drifted: under KOI_AUTH_TOKEN the
  // manual pick landed on `gpt-5.1-codex` (gateway openai default for
  // reasoning) which truncated the WORKFLOW.md translation to a single
  // task with maxTokens=1500. Letting the factory pick + raising
  // maxTokens to 3000 restores the full multi-task plan.
  await agent.llmProvider._ensureClients();
  let resolved;
  try {
    resolved = resolveModel({
      type: 'llm',
      taskType: 'reasoning',
      difficulty: 40,
      profile: { reasoningEffort: 'none' }, // force non-thinking — translator must be fast
      availableProviders: agent.llmProvider._availableProviders,
      clients: agent.llmProvider._gatewayMode
        ? agent.llmProvider._gatewayClients()
        : { openai: agent.llmProvider._oa, anthropic: agent.llmProvider._ac, gemini: agent.llmProvider._gc },
      temperature: 0,
      // 12K is the practical middle ground: 3K truncated JSON mid-string
      // on plans with rich Step-body descriptions, 16K pushed gpt-5.1
      // past the 30s default timeout (now 90s, but generation latency
      // still grows with maxTokens), 8K left no headroom for longer
      // workflows. 12K accommodates ~8 tasks with full descriptions
      // while keeping streaming time well inside 90s.
      maxTokens: 12000,
    });
  } catch (err) {
    return { tasks: [], fallback: true, reason: `No LLM candidates available for translator: ${err.message}` };
  }
  const llm = resolved.instance;

  const filesBlock = files.length === 0
    ? '(none beyond WORKFLOW.md)'
    : files.map(f => `  - ${f.path}${f.kind === 'dir' ? '/' : ''}`).join('\n');

  const prompt = `You are a workflow translator. A pre-approved workflow describes the ordered steps to complete a type of task. Your job is to INSTANTIATE those steps as concrete tasks for the user's current request.

Rules:
- One workflow step → one created task. Keep tasks at the same semantic
  granularity as the workflow's Step headings — never break a step into
  procedural sub-tasks like "fetch tool schema" or "look up parameter shape"
  (those are implementation details the executing agent handles inside the task).
- Do NOT invent new steps that are not present in the workflow.
- Do NOT research, explore, or redesign — the plan is already validated.
- You MAY omit a step if the user's message explicitly opts out of it.
- You MAY specialize wording so each task's description is actionable in context
  (e.g. substitute the user's actual topic, file paths, or constraints).
- Keep the original step order.
- Each task "description" must be self-contained: an executing agent will read ONLY
  that description (no conversation history). Include all needed context.
- When the workflow body references a sibling file by name (e.g. \`STORYBOARD_ANATOMY.md\`,
  \`STYLE_PRESETS.md\`, \`QUICK_START.md\`), substitute the FULL ABSOLUTE PATH from
  the WORKFLOW DIRECTORY listing below into the task description. Never leave a bare
  filename — the executing agent runs in the user's project, NOT in the workflow's
  own directory, and will not find the file by name.

USER REQUEST:
${(userMessage || '(no explicit user message)').substring(0, 1500)}

WORKFLOW: ${workflow.name}
WORKFLOW DESCRIPTION: ${workflow.description}
WORKFLOW DIRECTORY: ${workflow.directory || '(unknown)'}
WORKFLOW FILES (resolve sibling-file mentions to these absolute paths):
${filesBlock}

WORKFLOW BODY:
${body}

Return ONLY a JSON object with this shape, no prose, no markdown fences:
{
  "tasks": [
    { "subject": "<short imperative title>", "description": "<detailed, self-contained instructions>", "activeForm": "<present-continuous label, optional>" }
  ],
  "fallback": false
}

If the workflow does not actually match the user's request, return:
{ "tasks": [], "fallback": true, "reason": "<short explanation>" }`;

  try {
    // 90s timeout: with maxTokens=16000 the translator can take well over
    // 30s on slower reasoning models (gpt-5.1 with a 14k input prompt
    // routinely overshoots 30s and gets aborted mid-stream, killing the
    // whole activation). One-time call per activation — no reason to
    // race the clock.
    const { text } = await llm.complete([{ role: 'user', content: prompt }], { timeoutMs: 90000 });
    const stripped = (text || '').replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/, '').trim();
    if (!stripped) return { tasks: [], fallback: true, reason: 'Empty translator response' };

    const objMatch = stripped.match(/\{[\s\S]*\}/);
    const jsonToParse = objMatch ? objMatch[0] : stripped;
    const parsed = JSON.parse(jsonToParse);

    if (!Array.isArray(parsed.tasks)) {
      return { tasks: [], fallback: true, reason: 'Malformed translator output (tasks not an array)' };
    }
    return parsed;
  } catch (err) {
    channel.log('workflow', `Translator failed: ${err.message}`);
    return { tasks: [], fallback: true, reason: `Translator error: ${err.message}` };
  }
}

export default {
  type: 'run_workflow',
  intent: 'run_workflow',
  description: 'Run a workflow by name. Translates its WORKFLOW.md script into concrete tasks (via a cheap LLM), creates them, and fires planner.result to transition the System into running_plan. Call describe_workflow(name) FIRST to confirm the workflow matches your intent. Fields: "name" (required). → Returns: { activated, name, taskCount, fallback?, reason? }',
  thinkingHint: (action) => `Running workflow: ${action.name || '...'}`,
  permission: 'write_tasks',
  // Visible — see describe_workflow for the rationale. Without surfacing
  // this intent in AVAILABLE ACTIONS the coordinator never invokes it
  // even when AVAILABLE WORKFLOWS lists a perfect match.
  hidden: false,

  schema: {
    type: 'object',
    properties: {
      name: {
        type: 'string',
        description: 'The workflow name to run (e.g. "generate-article")',
      },
    },
    required: ['name'],
  },

  examples: [
    { actionType: 'direct', intent: 'run_workflow', name: 'generate-article' },
  ],

  async execute(action, agent) {
    const name = action.name;
    if (!name) return { activated: false, error: 'Missing required field: name' };

    const workflows = listWorkflowsCatalog();
    if (!workflows.length) {
      return { activated: false, error: 'No workflows configured' };
    }

    const workflow = workflows.find(w => w.name === name);
    if (!workflow) {
      const available = workflows.map(w => w.name).join(', ');
      return { activated: false, error: `Workflow "${name}" not found. Available: ${available}` };
    }

    const body = readWorkflowBody(workflow);
    if (body == null) {
      return { activated: false, error: `Failed to read ${workflow.location}` };
    }

    const userMessage =
      agent._lastUserMessage ||
      action.userMessage ||
      agent.state?.lastUserMessage ||
      '';

    // Enumerate sibling files of WORKFLOW.md so the translator can
    // substitute absolute paths into task descriptions, AND so we can
    // prepend the same listing to each task as a WORKFLOW WORKSPACE
    // block (belt-and-braces — even if the LLM forgets to substitute,
    // the executing agent has the absolute paths in front of it).
    const workflowFiles = listWorkflowFiles(workflow.directory);
    const workspace = workspaceBlock(workflow, workflowFiles);

    const translated = await runTranslator(agent, workflow, body, userMessage, workflowFiles);

    if (translated.fallback || !translated.tasks || translated.tasks.length === 0) {
      channel.log('workflow', `Workflow "${name}" fell back to routing: ${translated.reason || 'no tasks'}`);
      return {
        activated: false,
        name,
        fallback: true,
        reason: translated.reason || 'Translator produced no tasks',
      };
    }

    // Each workflow invocation gets a unique runId. Tasks created here
    // are tagged with it so agent.js can (a) find sibling completed
    // tasks for PRIOR STEPS injection and (b) point each step at a
    // shared on-disk workspace where heavy artifacts (HTML dumps,
    // downloads, intermediate files) persist between steps.
    const runId = `wfr-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
    const projectRoot = process.env.KOI_PROJECT_ROOT || process.cwd();
    const workspaceDir = path.join(projectRoot, '.koi', 'workflows', runId);
    try {
      fs.mkdirSync(workspaceDir, { recursive: true });
    } catch (err) {
      channel.log('workflow', `Could not create workspace ${workspaceDir}: ${err.message}`);
    }

    const createdIds = [];
    for (const t of translated.tasks) {
      if (!t || !t.subject || !t.description) continue;
      // Prepend the workspace block so the executing agent always knows
      // where the workflow files live, regardless of whether the
      // translator remembered to substitute absolute paths into the
      // body. Skipped when the workflow has no directory (defensive —
      // in practice every workflow has one because we discovered it
      // via scanDir).
      const description = workspace
        ? `${workspace}\n\n---\n\n${String(t.description)}`
        : String(t.description);
      try {
        const result = await agent.callAction('task_create', {
          subject: String(t.subject),
          description,
          activeForm: t.activeForm ? String(t.activeForm) : undefined,
          workflowRunId: runId,
        });
        if (result?.id) createdIds.push(result.id);
      } catch (err) {
        channel.log('workflow', `Failed to create task "${t.subject}": ${err.message}`);
      }
    }

    if (createdIds.length === 0) {
      return {
        activated: false,
        name,
        fallback: true,
        reason: 'No tasks were created (translator returned items but task_create rejected all)',
      };
    }

    await agent.callAction('update_state', {
      updates: { activeWorkflow: name, activeWorkflowRunId: runId },
    });

    channel.log('workflow', `Workflow activated: ${name} (${createdIds.length} tasks created)`);
    channel.workflowActivated({
      name,
      description: workflow.description,
      taskCount: createdIds.length,
      taskIds: createdIds,
    });

    const resultPayload = {
      success: true,
      data: { workflow: name, taskIds: createdIds },
      error: null,
      taskCount: createdIds.length,
      cancelled: false,
    };
    const reactionCtx = {
      planner: { result: resultPayload },
      any: { result: resultPayload },
      state: agent.state,
    };
    try {
      fireReaction(agent, 'planner.result', null, reactionCtx);
    } catch (err) {
      channel.log('workflow', `fireReaction(planner.result) failed: ${err.message}`);
    }

    return {
      activated: true,
      name,
      taskCount: createdIds.length,
      taskIds: createdIds,
    };
  },
};
