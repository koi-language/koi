/**
 * MCP media resolver — the SINGLE source of truth for "is a media MCP active
 * for this kind, and which one?". Used by BOTH:
 *   - factory.js  → to route generate_image/upscale/… to the MCP provider, and
 *   - action-registry.js → to label the banner ("vía Magnific") and to skip
 *     the credit/consent gate for MCP calls.
 * Routing and labelling therefore can never diverge.
 *
 * "Active" = a registered MCP client that is CONNECTED and whose media mapping
 * (explicit `media` block in .mcp.json, or a matched built-in profile) covers
 * the requested kind. Coexistence is per-kind: when no media MCP covers a kind,
 * this returns null and the caller falls back to the backend gateway.
 *
 * See docs/mcp-media-facade.md.
 */

import { mcpRegistry } from '../../mcp/mcp-registry.js';
import { currentMap, getDecision } from './mcp-media-store.js';

/**
 * Resolve the media mapping for a client. Routing to an MCP requires USER
 * OPT-IN — the facade never silently replaces the native backend:
 *   1. An explicit `media` block in .mcp.json always wins (manual override =
 *      implicit opt-in).
 *   2. Otherwise the AGENT-GENERATED map is used ONLY when the user has
 *      enabled this server for media (decision === 'enabled', set when they
 *      accept the detection dialog) AND the cached map still matches the
 *      current toolset hash (stale → null → regenerated by the mapper).
 * No hardcoded profiles — the map is always derived from the live tools.
 */
function resolveMediaConfig(name, client) {
  if (!client) return null;
  if (client.media && typeof client.media === 'object') return client.media;
  if (getDecision(name) !== 'enabled') return null;
  return currentMap(name, client);
}

/** Does this media mapping cover the given kind ('image'|'video'|'audio')? */
function coversKind(media, kind) {
  if (!media) return false;
  const gen = media.generate || {};
  if (gen[kind]) return true;
  // Image also covers the runOperation tools (upscale, bg-removal) and the
  // camera-angle reframe — all of which are image-typed at the factory level.
  if (kind === 'image') {
    if (media.operations && Object.keys(media.operations).length > 0) return true;
    if (media.cameraAngles) return true;
  }
  return false;
}

function labelFromName(name) {
  return name ? name.charAt(0).toUpperCase() + name.slice(1) : 'MCP';
}

/**
 * Find the active media MCP for a kind.
 * @param {'image'|'video'|'audio'} kind
 * @returns {{ server: string, label: string, media: object } | null}
 */
export function activeFor(kind) {
  try {
    for (const [name, client] of mcpRegistry.entries()) {
      if (!client) continue;
      // "Ready" = tools are loaded. NOT `client.connected`: the HTTP MCP client
      // sets `initialized` (not `connected`) after fetching its tools, so a
      // `!connected` check would never route to an HTTP server like Magnific.
      const ready = (Array.isArray(client.tools) && client.tools.length > 0)
        || client.connected || client.initialized;
      if (!ready) continue;
      const media = resolveMediaConfig(name, client);
      if (!media) continue;
      if (coversKind(media, kind)) {
        return { server: name, label: media.label || labelFromName(name), media };
      }
    }
  } catch { /* registry not ready / any error → treat as "no MCP" → backend */ }
  return null;
}
