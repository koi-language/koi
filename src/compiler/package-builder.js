/**
 * `koi build`: turns a .koi program into an npm package that TypeScript imports.
 *
 *   <out>/package.json   name, version, "type": "module", exports, types, the runtime as a dependency
 *   <out>/index.js       the program in library mode (see KoiTranspiler.generateLibraryExports)
 *   <out>/index.d.ts     one typed object per agent, one async method per public handler
 *
 * The runtime is NOT bundled: the package depends on `@koi-language/koi`, so the
 * consumer installs it once and every built package shares it.
 */

import { KoiTranspiler } from './transpiler.js';

const TS_RESERVED = new Set(['default', 'class', 'function', 'delete', 'new', 'in', 'import', 'export', 'enum', 'super', 'this', 'void', 'with', 'yield']);

/** A Koi type annotation as TypeScript. `top` is the handler's argument itself. */
export function koiTypeToTs(node, top = false) {
  if (!node) return top ? 'Record<string, any>' : 'any';
  switch (node.type) {
    case 'StringType': return 'string';
    case 'NumberType': return 'number';
    case 'BooleanType': return 'boolean';
    case 'VoidType': return 'void';
    case 'AnyType': return 'any';
    case 'NullType': return 'null';
    case 'UndefinedType': return 'undefined';
    case 'JsonType': return top ? 'Record<string, any>' : 'any';
    case 'ArrayTypeAnnotation': {
      const inner = koiTypeToTs(node.elementType);
      return /[|&\s]/.test(inner) ? `Array<${inner}>` : `${inner}[]`;
    }
    case 'UnionType': return node.types.map((t) => koiTypeToTs(t)).join(' | ');
    case 'ObjectTypeAnnotation': {
      const props = (node.properties || []).map((p) => `${JSON.stringify(p.name)}${p.optional ? '?' : ''}: ${koiTypeToTs(p.type)}`);
      return `{ ${props.join('; ')} }`;
    }
    case 'TypeAnnotation':
      switch (node.name) {
        case 'Promise': return `Promise<${koiTypeToTs(node.inner)}>`;
        case 'Int': return 'number';
        case 'String': return 'string';
        case 'Bool': return 'boolean';
        case 'Json': return top ? 'Record<string, any>' : 'any';
        default: return 'any'; // a type of the .koi program is not exported
      }
    default: return 'any';
  }
}

function _eventName(h) {
  return typeof h.event === 'string' ? h.event : h.event?.name;
}

function _affordance(h) {
  const stmt = (h.body || []).find((s) => s.type === 'AffordanceStatement' || s.type === 'AffordanceDecl');
  const v = stmt?.content?.value ?? stmt?.content;
  return typeof v === 'string' ? v.trim() : null;
}

function _doc(text, indent) {
  if (!text) return '';
  const safe = text.replace(/\*\//g, '*\\/').split('\n').map((l) => `${indent} * ${l}`.trimEnd());
  return `${indent}/**\n${safe.join('\n')}\n${indent} */\n`;
}

/** The handlers a package exposes for each agent, from the resolved AST. */
export function describeAgents(ast) {
  const agents = [];
  for (const decl of ast.declarations || []) {
    if (decl.type !== 'AgentDecl') continue;
    const handlers = (decl.body || [])
      .filter((b) => b.type === 'EventHandler' && !b.isPrivate)
      .map((h) => ({ name: _eventName(h), argType: koiTypeToTs(h.params?.[0]?.type, true), optional: !h.params?.length, doc: _affordance(h) }))
      .filter((h) => h.name);
    if (handlers.length) agents.push({ name: decl.name.name, handlers });
  }
  return agents;
}

/** index.d.ts: self-contained (the runtime ships no types), one declaration per agent. */
export function generateDts(agents) {
  let out = `// Generated by \`koi build\`. Do not edit: rebuild from the .koi source.

export interface KoiCallOptions {
  /** Reject with code KOI_TIMEOUT after this many milliseconds (the agent is aborted). */
  timeoutMs?: number;
  /** Reject with code KOI_ABORTED when it fires (the agent is aborted). */
  signal?: AbortSignal;
  /** Cap the steps of each agent session the call starts; reject with code KOI_MAX_STEPS. */
  maxSteps?: number;
  /** Approve shell commands, file writes and media costs without asking. Default: deny them. */
  autoApprove?: boolean;
  /** Everything the agent does: progress, actions, output, questions and answers. */
  onEvent?: (event: KoiEvent) => void;
  /** Answer the agent's questions. Return null/undefined to let it decide on its own. */
  onQuestion?: (question: KoiQuestion) => unknown | Promise<unknown>;
}

export interface KoiEvent {
  type: 'progress' | 'action' | 'output' | 'stream' | 'status' | 'question' | 'answer' | 'log';
  agent: string;
  [key: string]: unknown;
}

export interface KoiQuestion {
  kind: 'text' | 'select' | 'form';
  agent: string;
  question: string;
  choices?: Array<{ title: string; value: unknown }>;
  fields?: unknown[];
}

/** What a call rejects with. \`code\`: KOI_TIMEOUT, KOI_ABORTED, KOI_MAX_STEPS, KOI_AGENT_FAILED, KOI_UNKNOWN_HANDLER. */
export interface KoiCallError extends Error {
  code: string;
  agentName?: string;
}
`;
  for (const agent of agents) {
    out += `\nexport declare const ${agent.name}: {\n`;
    for (const h of agent.handlers) {
      const key = TS_RESERVED.has(h.name) ? JSON.stringify(h.name) : h.name;
      out += _doc(h.doc, '  ');
      out += `  ${key}(args${h.optional ? '?' : ''}: ${h.argType}, options?: KoiCallOptions): Promise<any>;\n`;
    }
    out += `};\n`;
  }
  return out;
}

/** package.json of the built package. */
export function generatePackageJson({ name, version = '0.1.0', description, koiDependency, sourceFile }) {
  return JSON.stringify({
    name,
    version,
    description: description || `Koi agents built from ${sourceFile}`,
    type: 'module',
    main: './index.js',
    types: './index.d.ts',
    exports: { '.': { types: './index.d.ts', import: './index.js' } },
    files: ['index.js', 'index.d.ts'],
    dependencies: { '@koi-language/koi': koiDependency },
    koi: { source: sourceFile },
  }, null, 2) + '\n';
}

/** A valid npm package name from a file name. */
export function packageNameFrom(base) {
  const n = String(base).toLowerCase().replace(/\.koi$/, '').replace(/[^a-z0-9._-]+/g, '-').replace(/^[-._]+|[-._]+$/g, '');
  return n || 'koi-agents';
}

